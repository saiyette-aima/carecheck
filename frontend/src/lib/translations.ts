// Call free translate API on the frontend (MyMemory)
export async function translateDynamicText(text: string, targetLang: string): Promise<string> {
  if (!text || !targetLang || targetLang === "en") return text;
  
  // Clean text and check in-memory cache first to avoid excessive network requests
  const cacheKey = `${targetLang}:${text}`;
  try {
    const cached = localStorage.getItem(`trans_cache_${cacheKey}`);
    if (cached) return cached;
  } catch (e) {
    // LocalStorage might be disabled or full
  }
  
  try {
    const res = await fetch(
      `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=en|${targetLang}&de=carecheck-app@gmail.com`
    );
    if (res.ok) {
      const data = await res.json();
      const translated = data.responseData?.translatedText;
      if (translated) {
        // Save to cache
        try {
          localStorage.setItem(`trans_cache_${cacheKey}`, translated);
        } catch (e) {
          // ignore cache writing errors
        }
        return translated;
      }
    }
  } catch (e) {
    console.error("Dynamic translation error:", e);
  }
  return text;
}
